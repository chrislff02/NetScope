@asynccontextmanager
async def lifespan(app: FastAPI):
    """
    Manage NetScope's broadcaster and Unix socket receiver
    alongside the FastAPI application.
    """

    # Create one broadcaster for this application instance.
    broadcaster = PacketBroadcaster()
    app.state.packet_broadcaster = broadcaster

    # Used to confirm that the receiver has started.
    ready_event = asyncio.Event()

    # Start the receiver without blocking FastAPI startup.
    receiver_task = asyncio.create_task(
        start_receiver(
            on_packet=broadcaster.publish,
            ready_event=ready_event,
        )
    )

    ready_task = asyncio.create_task(ready_event.wait())

    try:
        # Wait for either successful startup or an early failure.
        done, _ = await asyncio.wait(
            {receiver_task, ready_task},
            timeout=5,
            return_when=asyncio.FIRST_COMPLETED,
        )

        if receiver_task in done:
            # Propagate the actual startup error to FastAPI.
            await receiver_task

            raise RuntimeError(
                "Packet receiver exited during startup."
            )

        if ready_task not in done:
            raise RuntimeError(
                "Packet receiver startup timed out."
            )

        print("NetScope packet receiver is ready.")

        # FastAPI can now serve HTTP and WebSocket requests.
        yield

    finally:
        ready_task.cancel()
        await asyncio.gather(
            ready_task,
            return_exceptions=True,
        )

        # Stop the receiver on shutdown or failed startup.
        receiver_task.cancel()
        await asyncio.gather(
            receiver_task,
            return_exceptions=True,
        )

        print("NetScope packet receiver stopped.")


# Create our FastAPI application.
app = FastAPI(
    title="NetScope API",
    description="Network Traffic Analysis API",
    version="1.0.0",
    lifespan=lifespan,
)


# Locate the sample PCAP file.
BASE_DIR = Path(__file__).resolve().parent.parent
PCAP_FILE = BASE_DIR / "samples" / "sample_traffic.pcap"

# Location of the latest completed live capture.
LIVE_CAPTURE_FILE = BASE_DIR / "data" / "live_capture.json"


@lru_cache(maxsize=1)
def load_packet_records():
    # Load sample traffic and cache the results.
    if not PCAP_FILE.exists():
        raise HTTPException(
            status_code=404,
            detail="Sample PCAP file not found."
        )

    packets = rdpcap(str(PCAP_FILE))
    records = []

    # Convert Scapy packets into dictionaries.
    for packet in packets:
        record = packet_to_dict(packet)

        if record is not None:
            records.append(record)

    return records


@app.get("/api/health")
def health_check():
    # Confirm that our API is running.
    return {
        "status": "healthy",
        "application": "NetScope",
    }


@app.get("/api/traffic/summary")
def get_traffic_summary():
    # Return our calculated network statistics.
    records = load_packet_records()
    return calculate_statistics(records)


@app.get("/api/traffic/packets")
def get_packets():
    # Return individual packet records.
    records = load_packet_records()

    return {
        "total": len(records),
        "packets": records,
    }


@app.get("/api/traffic/timeline")
def get_traffic_timeline():
    # Return traffic grouped by second.
    records = load_packet_records()
    statistics = calculate_statistics(records)

    return statistics["traffic_over_time"]


@app.get("/api/capture/latest")
def get_latest_capture():
    # Verify that a completed capture file exists.
    if not LIVE_CAPTURE_FILE.is_file():
        raise HTTPException(
            status_code=404,
            detail="No live capture file found.",
        )

    try:
        # Read the JSON generated by live_capture.py.
        with open(
            LIVE_CAPTURE_FILE,
            "r",
            encoding="utf-8",
        ) as file:
            capture_data = json.load(file)

    except PermissionError:
        raise HTTPException(
            status_code=403,
            detail="Cannot read the live capture file.",
        )

    except (json.JSONDecodeError, UnicodeDecodeError):
        raise HTTPException(
            status_code=500,
            detail="Live capture file contains invalid JSON.",
        )

    # Check for the required fields.
    if (
        not isinstance(capture_data, dict)
        or not isinstance(capture_data.get("packets"), list)
        or not isinstance(capture_data.get("statistics"), dict)
    ):
        raise HTTPException(
            status_code=500,
            detail="Live capture file has an invalid structure.",
        )

    # Return packet metadata and statistics.
    return capture_data


